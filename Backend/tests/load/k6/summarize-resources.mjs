import { readFile, writeFile } from 'node:fs/promises';

/**
 * @typedef {Object} NumericSummary
 * @property {number} count Number of valid samples.
 * @property {number|null} min Minimum sample.
 * @property {number|null} avg Arithmetic mean.
 * @property {number|null} p50 Median sample.
 * @property {number|null} p95 95th percentile sample.
 * @property {number|null} max Maximum sample.
 * @property {number|null} sum Sum of samples; useful for per-interval Rate counters.
 * @property {number|null} first First sample in collection order.
 * @property {number|null} last Last sample in collection order.
 * @property {number|null} delta Last minus first, useful for cumulative runtime counters.
 */

/**
 * Parses one RFC-4180-style CSV row, including escaped quotes and embedded commas.
 *
 * @param {string} line CSV row.
 * @returns {string[]} Parsed fields.
 */
function parseCsvRow(line) {
    const fields = [];
    let field = '';
    let quoted = false;
    for (let index = 0; index < line.length; index += 1) {
        const character = line[index];
        if (character === '"') {
            if (quoted && line[index + 1] === '"') {
                field += '"';
                index += 1;
            } else {
                quoted = !quoted;
            }
        } else if (character === ',' && !quoted) {
            fields.push(field);
            field = '';
        } else {
            field += character;
        }
    }
    fields.push(field);
    return fields;
}

/**
 * Reads a CSV document into objects keyed by its header names.
 *
 * @param {string} path CSV file path.
 * @returns {Promise<Object[]>} Parsed records.
 */
async function readCsv(path) {
    const text = (await readFile(path, 'utf8')).replace(/^\uFEFF/, '').trim();
    if (!text) return [];
    const rows = text.split(/\r?\n/).filter((line) => line.length > 0).map(parseCsvRow);
    const headers = rows.shift().map((header) => header.trim());
    return rows.map((row) => Object.fromEntries(headers.map((header, index) => [header, row[index] ?? ''])));
}

/**
 * Calculates a linearly selected percentile from sorted observations.
 *
 * @param {number[]} sortedValues Values sorted in ascending order.
 * @param {number} percentile Percentile in the inclusive range 0..1.
 * @returns {number|null} Selected observation or null for an empty set.
 */
function percentile(sortedValues, percentileValue) {
    if (sortedValues.length === 0) return null;
    return sortedValues[Math.ceil(percentileValue * sortedValues.length) - 1] ?? sortedValues[0];
}

/**
 * Aggregates a time-ordered numeric series.
 *
 * @param {number[]} input Raw numeric samples.
 * @returns {NumericSummary} Stable statistical summary.
 */
function summarize(input) {
    const values = input.filter(Number.isFinite);
    if (values.length === 0) {
        return { count: 0, min: null, avg: null, p50: null, p95: null, max: null, sum: null,
            first: null, last: null, delta: null };
    }
    const sorted = [...values].sort((left, right) => left - right);
    const first = values[0];
    const last = values[values.length - 1];
    return {
        count: values.length,
        min: sorted[0],
        avg: values.reduce((total, value) => total + value, 0) / values.length,
        p50: percentile(sorted, 0.50),
        p95: percentile(sorted, 0.95),
        max: sorted[sorted.length - 1],
        sum: values.reduce((total, value) => total + value, 0),
        first,
        last,
        delta: last - first,
    };
}

/**
 * Converts a CSV field to a number, tolerating whitespace and invariant thousands separators.
 *
 * @param {string|undefined} value CSV field.
 * @returns {number} Parsed value or NaN.
 */
function numeric(value) {
    return Number((value ?? '').trim().replace(/(?<=\d),(?=\d{3}(?:\D|$))/g, ''));
}

/**
 * Finds a field by case-insensitive header aliases.
 *
 * @param {Object} row CSV record.
 * @param {string[]} aliases Lowercase header names or fragments.
 * @returns {string|undefined} Matching field value.
 */
function findField(row, aliases) {
    const entry = Object.entries(row).find(([key]) => {
        const normalized = key.trim().toLowerCase();
        return aliases.some((alias) => normalized === alias || normalized.includes(alias));
    });
    return entry ? entry[1] : undefined;
}

/**
 * Aggregates the platform-neutral process sampler generated by the launcher scripts.
 *
 * @param {Object[]} rows Process sample records.
 * @returns {Object} CPU, memory, and thread statistics.
 */
function summarizeProcess(rows) {
    const column = (name) => rows.map((row) => numeric(row[name]));
    return {
        sampleCount: rows.length,
        cpuPercent: summarize(column('cpu_percent')),
        workingSetBytes: summarize(column('working_set_bytes')),
        privateMemoryBytes: summarize(column('private_memory_bytes')),
        virtualMemoryBytes: summarize(column('virtual_memory_bytes')),
        threadCount: summarize(column('thread_count')),
    };
}

/**
 * Aggregates every numeric dotnet-counters series without depending on a particular .NET version.
 * Runtime metric names and dimensions are preserved as report keys.
 *
 * @param {Object[]} rows dotnet-counters CSV records.
 * @returns {Object<string, NumericSummary>} Runtime counter summaries.
 */
function summarizeRuntimeCounters(rows) {
    /** @type {Map<string, number[]>} */
    const series = new Map();
    for (const row of rows) {
        const provider = findField(row, ['provider']) ?? 'unknown-provider';
        const counter = findField(row, ['counter name', 'countername', 'meter', 'instrument']) ?? 'unknown-counter';
        const counterType = findField(row, ['counter type', 'countertype']) ?? '';
        const value = numeric(findField(row, ['mean/increment', 'value', 'mean', 'increment']));
        if (!Number.isFinite(value)) continue;
        const key = [provider, counter, counterType].filter((part) => part.length > 0).join(' :: ');
        if (!series.has(key)) series.set(key, []);
        series.get(key).push(value);
    }
    return Object.fromEntries([...series.entries()].sort(([left], [right]) => left.localeCompare(right))
        .map(([key, values]) => [key, summarize(values)]));
}

/**
 * Creates resource-summary.json from process and CLR counter streams.
 *
 * @returns {Promise<void>}
 */
async function main() {
    const [, , processCsvPath, countersCsvPath, outputPath] = process.argv;
    if (!processCsvPath || !countersCsvPath || !outputPath) {
        throw new Error('Usage: node summarize-resources.mjs <process.csv> <counters.csv> <output.json>');
    }
    const [processRows, counterRows] = await Promise.all([readCsv(processCsvPath), readCsv(countersCsvPath)]);
    const result = {
        schemaVersion: 1,
        generatedAt: new Date().toISOString(),
        process: summarizeProcess(processRows),
        runtimeCounters: summarizeRuntimeCounters(counterRows),
    };
    await writeFile(outputPath, JSON.stringify(result, null, 2), 'utf8');
    console.log(`Resource summary: ${outputPath}`);
}

await main();
